# scripts/demos/demo_rq_valuation_engine_throughput_benchmarking.py
"""
Bare-metal throughput benchmarking for all compiled RiskQuant pricing kernels.

This script isolates the kernels from the portfolio and dispatch layers, feeding
them raw C-contiguous arrays to measure the absolute ceiling of the hardware's
memory bandwidth and SIMD utilization.
"""

import time

import numpy as np

from riskquant.valuation.pricer_kernels.fixed_cashflow import (
    _kernel_price_fixed_cashflow,
)
from riskquant.valuation.pricer_kernels.floating_cashflow import (
    _kernel_price_floating_cashflow,
)
from riskquant.valuation.pricer_kernels.principal_cashflow import (
    _kernel_price_principal_cashflow,
)

# --- IMPORT KERNELS ---
from riskquant.valuation.pricer_kernels.spot import _kernel_price_spot
from riskquant.valuation.pricer_kernels.vanilla_european_option import (
    _kernel_price_vanilla_european_option,
)
from riskquant.valuation.pricer_kernels.vanilla_forward import (
    _kernel_price_vanilla_forward,
)

# --- BENCHMARK CONFIGURATION ---
# Adjust these to fit into your L3 cache or to blow past it to test RAM bandwidth.
N_TRADES = 100_000
N_SCENARIOS = 5_000
N_UIX = 100  # Number of unique curves/FX/vols generated by the "compiler"
NUM_RUNS = 5  # Number of timed iterations per kernel

TOTAL_PVS = N_TRADES * N_SCENARIOS


# --- GENERATOR HELPERS ---
def _f64_1d() -> np.ndarray:
    return np.random.uniform(0.1, 100.0, size=N_TRADES).astype(np.float64)


def _f64_2d(rows: int) -> np.ndarray:
    return np.random.uniform(0.1, 100.0, size=(rows, N_SCENARIOS)).astype(np.float64)


def _uix_1d() -> np.ndarray:
    return np.random.randint(0, N_UIX, size=N_TRADES, dtype=np.int32)


def _cp_mult() -> np.ndarray:
    return np.random.choice([1, -1], size=N_TRADES).astype(np.int8)


# --- ALLOCATE FAKE MARKET DATA (THE "VALUATION STATE") ---
md_effective_spot = _f64_2d(N_UIX)
md_effective_fwd = _f64_2d(N_UIX)
md_effective_df = _f64_2d(N_UIX)

md_fwd_strike_ccy = _f64_2d(rows=N_UIX)
md_log_fwd_strike_ccy = np.log(md_fwd_strike_ccy)

md_vols = _f64_2d(N_UIX)
md_fwd_rates = _f64_2d(N_UIX)


def run_benchmarks() -> None:
    print("============================================================")
    print(" RISKQUANT KERNEL THROUGHPUT BENCHMARK")
    print("============================================================")
    print(f" Trades    : {N_TRADES:,}")
    print(f" Scenarios : {N_SCENARIOS:,}")
    print(f" Runs/Knl  : {NUM_RUNS}")
    print(f" Total PVs : {TOTAL_PVS:,} per run")
    print("============================================================\n")

    benchmarks = [
        ("Spot", benchmark_spot),
        ("Principal Cashflow", benchmark_principal_cashflow),
        ("Fixed Cashflow", benchmark_fixed_cashflow),
        ("Floating Cashflow", benchmark_floating_cashflow),
        ("Vanilla Forward", benchmark_vanilla_forward),
        ("Vanilla European Option", benchmark_vanilla_european_option),
    ]

    for name, func in benchmarks:
        print(f"Benchmarking: {name}")

        # 1. Warm-up (triggers LLVM compilation)
        func(warmup=True)

        # 2. Allocate clean output buffer
        out = np.zeros((N_TRADES, N_SCENARIOS), dtype=np.float64)

        run_times = []

        # 3. Timed runs
        for _ in range(NUM_RUNS):
            t0 = time.perf_counter()
            func(warmup=False, out=out)
            t1 = time.perf_counter()
            run_times.append(t1 - t0)

        # 4. Calculate Statistics
        avg_time = sum(run_times) / NUM_RUNS
        min_time = min(run_times)
        max_time = max(run_times)

        avg_pvs_per_sec = TOTAL_PVS / avg_time
        peak_pvs_per_sec = TOTAL_PVS / min_time

        print(
            f"  -> Avg Time : {avg_time:.4f} sec  [Best: {min_time:.4f}s | Worst: {max_time:.4f}s]"
        )
        print(f"  -> Avg Speed: {avg_pvs_per_sec / 1e9:.3f} Billion PVs / sec")
        print(f"  -> Peak Spd : {peak_pvs_per_sec / 1e9:.3f} Billion PVs / sec\n")


# ==============================================================================
# INDIVIDUAL KERNEL BENCHMARKS
# ==============================================================================


def benchmark_spot(warmup: bool, out: np.ndarray = None) -> None:
    qty = _f64_1d()
    eff_spot_uix = _uix_1d()

    if warmup:
        _kernel_price_spot(
            np.zeros((2, 2)), md_effective_spot, qty[:2], eff_spot_uix[:2]
        )
    else:
        _kernel_price_spot(out, md_effective_spot, qty, eff_spot_uix)


def benchmark_principal_cashflow(warmup: bool, out: np.ndarray = None) -> None:
    amount = _f64_1d()
    eff_df_uix = _uix_1d()

    if warmup:
        _kernel_price_principal_cashflow(
            np.zeros((2, 2)), md_effective_df, amount[:2], eff_df_uix[:2]
        )
    else:
        _kernel_price_principal_cashflow(out, md_effective_df, amount, eff_df_uix)


def benchmark_fixed_cashflow(warmup: bool, out: np.ndarray = None) -> None:
    notional = _f64_1d()
    accrual = _f64_1d()
    rate = _f64_1d()
    pay_rec = _cp_mult()
    eff_df_uix = _uix_1d()

    if warmup:
        _kernel_price_fixed_cashflow(
            np.zeros((2, 2)),
            md_effective_df,
            notional[:2],
            accrual[:2],
            rate[:2],
            pay_rec[:2],
            eff_df_uix[:2],
        )
    else:
        _kernel_price_fixed_cashflow(
            out, md_effective_df, notional, accrual, rate, pay_rec, eff_df_uix
        )


def benchmark_floating_cashflow(warmup: bool, out: np.ndarray = None) -> None:
    notional = _f64_1d()
    accrual = _f64_1d()
    spread = _f64_1d()
    pay_rec = _cp_mult()
    fwd_rate_uix = _uix_1d()
    eff_df_uix = _uix_1d()

    if warmup:
        _kernel_price_floating_cashflow(
            np.zeros((2, 2)),
            md_fwd_rates,
            md_effective_df,
            notional[:2],
            accrual[:2],
            spread[:2],
            pay_rec[:2],
            fwd_rate_uix[:2],
            eff_df_uix[:2],
        )
    else:
        _kernel_price_floating_cashflow(
            out,
            md_fwd_rates,
            md_effective_df,
            notional,
            accrual,
            spread,
            pay_rec,
            fwd_rate_uix,
            eff_df_uix,
        )


def benchmark_vanilla_forward(warmup: bool, out: np.ndarray = None) -> None:
    qty = _f64_1d()
    strike = _f64_1d()
    eff_fwd_uix = _uix_1d()
    eff_df_uix = _uix_1d()

    if warmup:
        _kernel_price_vanilla_forward(
            np.zeros((2, 2)),
            md_effective_fwd,
            md_effective_df,
            qty[:2],
            strike[:2],
            eff_fwd_uix[:2],
            eff_df_uix[:2],
        )
    else:
        _kernel_price_vanilla_forward(
            out, md_effective_fwd, md_effective_df, qty, strike, eff_fwd_uix, eff_df_uix
        )


def benchmark_vanilla_european_option(warmup: bool, out: np.ndarray = None) -> None:
    qty = _f64_1d()

    strike = _f64_1d()
    log_strike = np.log(strike)

    cp_mult = _cp_mult()
    sqrt_tte = _f64_1d()
    half_tte = _f64_1d()

    fwd_uix = _uix_1d()
    log_fwd_uix = _uix_1d()
    vol_uix = _uix_1d()
    eff_df_uix = _uix_1d()

    if warmup:
        _kernel_price_vanilla_european_option(
            np.zeros((2, 2)),
            md_fwd_strike_ccy,
            md_log_fwd_strike_ccy,
            md_vols,
            md_effective_df,
            qty[:2],
            strike[:2],
            log_strike[:2],
            cp_mult[:2],
            sqrt_tte[:2],
            half_tte[:2],
            fwd_uix[:2],
            log_fwd_uix[:2],
            vol_uix[:2],
            eff_df_uix[:2],
        )
    else:
        _kernel_price_vanilla_european_option(
            out,
            md_fwd_strike_ccy,
            md_log_fwd_strike_ccy,
            md_vols,
            md_effective_df,
            qty,
            strike,
            log_strike,
            cp_mult,
            sqrt_tte,
            half_tte,
            fwd_uix,
            log_fwd_uix,
            vol_uix,
            eff_df_uix,
        )


if __name__ == "__main__":
    run_benchmarks()
