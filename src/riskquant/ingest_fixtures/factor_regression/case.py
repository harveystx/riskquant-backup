# src/riskquant/ingest_fixtures/factor_regression/case.py
"""
Edge contract of the canonical factor-regression fixture.

One case is one business question plus the raw observations that answer it.
Observations are a Polars long frame, one row per (series, observed date). This
is the shape a data gateway delivers: the fixture holds no NaN, no fill and no
pre-aligned matrix. A missing observation is an absent row. Alignment is the
job of ``riskquant.solutions.factor_regression.api.align_levels``.

``truth`` holds the data-generating parameters. The analyses catalog
(``analyses.py``) and the fixture tests compare estimates against it.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from datetime import date
from types import MappingProxyType
from typing import Final

import numpy as np
import numpy.typing as npt
import polars as pl

from riskquant.ingest_fixtures.factor_regression.calendars import (
    GRID_SIZE,
    WEEKDAY_GRID_ORD,
)
from riskquant.utils.business_days import date_to_ord

__all__ = [
    "FACTOR_REGRESSION_SERIES_SCHEMA",
    "FactorRegressionCase",
    "SeriesObservations",
    "build_series_frame",
    "observe",
]

FACTOR_REGRESSION_SERIES_SCHEMA: Final[pl.Schema] = pl.Schema({
    "case": pl.Utf8,
    "series_name": pl.Utf8,
    "unit": pl.Utf8,
    "date": pl.Date,
    "value": pl.Float64,
})


@dataclass(frozen=True, slots=True, kw_only=True, eq=False)
class SeriesObservations:
    """
    Observations of one series before they become frame rows.

    ``eq=False``: an autogenerated ``__eq__`` compares arrays element-wise.
    """

    name: str
    unit: str
    date_ord: npt.NDArray[np.int32]
    values: npt.NDArray[np.float64]


def observe(
    *,
    name: str,
    unit: str,
    grid_values: npt.NDArray[np.float64],
    mask: npt.NDArray[np.bool_],
) -> SeriesObservations:
    """
    Keep the grid days of ``mask``: the series is observed on those days only.

    Raises
    ------
    ValueError
        ``grid_values`` or ``mask`` does not have the grid length.
    """
    if grid_values.shape != (GRID_SIZE,) or mask.shape != (GRID_SIZE,):
        raise ValueError(f"{name}: grid_values and mask must have shape ({GRID_SIZE},)")
    keep = np.flatnonzero(mask)
    return SeriesObservations(
        name=name,
        unit=unit,
        date_ord=np.ascontiguousarray(WEEKDAY_GRID_ORD[keep]),
        values=np.ascontiguousarray(grid_values[keep], dtype=np.float64),
    )


def build_series_frame(case: str, series: Sequence[SeriesObservations]) -> pl.DataFrame:
    """
    Stack ``series`` into one long frame with ``FACTOR_REGRESSION_SERIES_SCHEMA``.

    Raises
    ------
    ValueError
        A name repeats, an array has the wrong dtype or length, a date axis is
        not strictly increasing, or a value is not finite. The fixture fails
        at import time rather than ship a frame that the facade rejects later.
    """
    names = [s.name for s in series]
    if len(set(names)) != len(names):
        raise ValueError(f"{case}: repeated series name in {names}")
    blocks: list[pl.DataFrame] = []
    for s in series:
        if s.date_ord.dtype != np.int32 or s.values.dtype != np.float64:
            raise ValueError(f"{case}/{s.name}: date_ord int32 and values float64")
        if s.date_ord.shape != s.values.shape or s.date_ord.ndim != 1:
            raise ValueError(f"{case}/{s.name}: date_ord and values shape mismatch")
        if not bool(np.all(s.date_ord[1:] > s.date_ord[:-1])):
            raise ValueError(f"{case}/{s.name}: date_ord not strictly increasing")
        with np.errstate(all="ignore"):
            finite = bool(np.isfinite(s.values).all())
        if not finite:
            raise ValueError(f"{case}/{s.name}: non-finite value")
        n = int(s.values.shape[0])
        blocks.append(
            pl.DataFrame({
                "case": pl.Series([case] * n, dtype=pl.Utf8),
                "series_name": pl.Series([s.name] * n, dtype=pl.Utf8),
                "unit": pl.Series([s.unit] * n, dtype=pl.Utf8),
                # pl.Date is an int32 day count from 1970-01-01: the cast is
                # exact and matches the riskquant date ordinal.
                "date": pl.Series(s.date_ord, dtype=pl.Int32).cast(pl.Date),
                "value": pl.Series(s.values, dtype=pl.Float64),
            })
        )
    frame = pl.concat(blocks, how="vertical")
    if frame.schema != FACTOR_REGRESSION_SERIES_SCHEMA:
        raise ValueError(f"{case}: frame schema {frame.schema} is not canonical")
    return frame


@dataclass(frozen=True, slots=True, kw_only=True, eq=False)
class FactorRegressionCase:
    """
    One canonical business question and its raw observations.

    Parameters
    ----------
    name
        Stable case key; equals the ``case`` column of ``frame``.
    question
        The business question the case answers, in one sentence.
    series_names
        Series of ``frame`` in their canonical order.
    window_start, window_end
        Declared half-open window ``[window_start, window_end)``.
    truth
        Data-generating parameters, read-only.
    frame
        Long frame with ``FACTOR_REGRESSION_SERIES_SCHEMA``.

    ``eq=False``: ``frame`` is not comparable with ``==``.
    """

    name: str
    question: str
    series_names: tuple[str, ...]
    window_start: date
    window_end: date
    truth: Mapping[str, float]
    frame: pl.DataFrame

    def __post_init__(self) -> None:
        object.__setattr__(self, "truth", MappingProxyType(dict(self.truth)))
        if self.window_start >= self.window_end:
            raise ValueError(f"{self.name}: empty window")
        if self.frame.schema != FACTOR_REGRESSION_SERIES_SCHEMA:
            raise ValueError(f"{self.name}: frame schema is not canonical")
        present = tuple(
            self.frame.get_column("series_name").unique(maintain_order=True)
        )
        if present != self.series_names:
            raise ValueError(
                f"{self.name}: frame series {present} != series_names "
                f"{self.series_names}"
            )

    @property
    def start_ord(self) -> int:
        """``int32`` date ordinal of ``window_start``."""
        return date_to_ord(self.window_start)

    @property
    def end_ord(self) -> int:
        """``int32`` date ordinal of ``window_end`` (exclusive)."""
        return date_to_ord(self.window_end)
