# src/riskquant/config/proxy_model/compiled.py
"""
The compiled, run-bound Proxy V1 operator (D088 §2, §6, §7).

Semantic object
---------------
For every V1 target-axis node ``A`` of one run (in run-axis order):

    X_A = sum_j beta_Aj * Y(d_j, tau_j, h)

The compiled model is the canonical resolved operator AFTER totality closure
against the run axis: every V1 axis node has exactly one row, and a node with no
authored terms carries its materialised identity row ``(A, kappa_A, 1.0)``.
It is therefore a function of (authored terms, static configuration, as-of,
run axis) and is not a universal, run-independent object.

Representation (CSR over rows)
------------------------------
``row_target_rf_ids``   (R,)    int32   target node per row, run-axis order
``row_term_offsets``    (R+1,)  int32   row r owns terms [off[r], off[r+1])
``term_driver_rf_ids``  (T,)    int32   driver node per term
``term_chart_ids``      (T,)    int8    driver chart tau per term, {1, 2, 3}
``term_loadings``       (T,)    float64 canonical merged beta per term

What is deliberately absent
---------------------------
* The target chart ``kappa_A``: owned by the target factor definition and
  carried by the run axis (D088 §3). It appears here only as the driver chart
  of a materialised identity term, where ``tau == kappa_A`` by definition.
* The horizon ``h`` and step unit: owned by the scenario world (D088 §3, §4).
* Column indices, scenario counts, batches, base levels: runtime bindings.
* ABSOLUTE_BASE / NO_SHIFT axis nodes: they keep their D025 native path and are
  not rows of the V1 proxy model (D088 §1).
* A stored digest: identity is ``hash_proxy_model(model)`` in the run-identity
  layer, computed from these arrays (D088 §7); storing it would duplicate truth.

Every array is an owned, read-only, C-contiguous copy, so identity cannot drift
through aliasing after construction.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import numpy.typing as npt

from riskquant.market_data.risk_factors.shift_types import ShiftType

__all__ = [
    "V1_DRIVER_CHART_IDS",
    "V1_TARGET_CHART_IDS",
    "CompiledProxyModel",
]

# D088 §1: V1 reconstruction charts and V1 driver-chart catalogue coincide.
# ABSOLUTE_BASE_RETURN and NO_SHIFT are excluded from both (D025 native path).
V1_TARGET_CHART_IDS: frozenset[int] = frozenset(
    {
        int(ShiftType.LOG_RETURN),
        int(ShiftType.SIMPLE_RETURN),
        int(ShiftType.DIFFERENCE),
    }
)
V1_DRIVER_CHART_IDS: frozenset[int] = V1_TARGET_CHART_IDS

_FIELD_DTYPES: tuple[tuple[str, np.dtype[np.generic]], ...] = (
    ("row_target_rf_ids", np.dtype(np.int32)),
    ("row_term_offsets", np.dtype(np.int32)),
    ("term_driver_rf_ids", np.dtype(np.int32)),
    ("term_chart_ids", np.dtype(np.int8)),
    ("term_loadings", np.dtype(np.float64)),
)


def _owned_read_only(
    name: str, value: object, dtype: np.dtype[np.generic]
) -> npt.NDArray[np.generic]:
    """Validate exact dtype and rank, then return a frozen C-contiguous copy."""
    if not isinstance(value, np.ndarray):
        raise TypeError(f"{name} must be a numpy.ndarray, got {type(value).__name__}.")
    if value.dtype != dtype:
        raise TypeError(f"{name} must have dtype {dtype}, got {value.dtype}.")
    if value.ndim != 1:
        raise ValueError(f"{name} must be 1-D, got shape {value.shape}.")
    owned = np.array(value, dtype=dtype, copy=True, order="C")
    owned.setflags(write=False)
    return owned


@dataclass(frozen=True, slots=True, kw_only=True, eq=False)
class CompiledProxyModel:
    """
    Canonical run-bound Proxy V1 operator in CSR form.

    Construction validates every structural invariant of the canonical form,
    so an instance is canonical by construction:

    * ``row_term_offsets[0] == 0``, ``row_term_offsets[-1] == T`` and every row
      is non-empty (strictly increasing offsets);
    * ``row_target_rf_ids`` are non-negative and unique;
    * ``term_driver_rf_ids`` are non-negative;
    * ``term_chart_ids`` lie in the V1 driver-chart catalogue;
    * ``term_loadings`` are finite and non-zero (no signed zero survives);
    * within a row, ``(driver_rf_id, chart_id)`` is strictly increasing, so no
      duplicate term exists and the term order is canonical.

    ``eq=False``: an autogenerated ``__eq__`` would compare arrays elementwise.
    Compare models through ``hash_proxy_model``.
    """

    row_target_rf_ids: npt.NDArray[np.int32]
    row_term_offsets: npt.NDArray[np.int32]
    term_driver_rf_ids: npt.NDArray[np.int32]
    term_chart_ids: npt.NDArray[np.int8]
    term_loadings: npt.NDArray[np.float64]

    def __post_init__(self) -> None:
        for name, dtype in _FIELD_DTYPES:
            object.__setattr__(
                self, name, _owned_read_only(name, getattr(self, name), dtype)
            )

        targets = self.row_target_rf_ids
        offsets = self.row_term_offsets
        drivers = self.term_driver_rf_ids
        charts = self.term_chart_ids
        loadings = self.term_loadings

        n_rows = targets.shape[0]
        n_terms = drivers.shape[0]
        if offsets.shape[0] != n_rows + 1:
            raise ValueError(
                f"row_term_offsets must have length {n_rows + 1} (rows + 1), "
                f"got {offsets.shape[0]}."
            )
        if charts.shape[0] != n_terms or loadings.shape[0] != n_terms:
            raise ValueError(
                "term arrays must share one length: "
                f"drivers={n_terms}, charts={charts.shape[0]}, "
                f"loadings={loadings.shape[0]}."
            )
        if int(offsets[0]) != 0 or int(offsets[-1]) != n_terms:
            raise ValueError(
                f"row_term_offsets must start at 0 and end at {n_terms}; got "
                f"[{int(offsets[0])} .. {int(offsets[-1])}]."
            )
        if n_rows and not bool(np.all(np.diff(offsets) > 0)):
            raise ValueError(
                "every canonical row must own at least one term "
                "(row_term_offsets must be strictly increasing)."
            )
        if n_rows and int(targets.min()) < 0:
            raise ValueError("row_target_rf_ids must be non-negative rf_ids.")
        if np.unique(targets).shape[0] != n_rows:
            raise ValueError("row_target_rf_ids must be unique (one row per target).")
        if n_terms and int(drivers.min()) < 0:
            raise ValueError("term_driver_rf_ids must be non-negative rf_ids.")
        if n_terms and not bool(
            np.isin(charts, np.array(sorted(V1_DRIVER_CHART_IDS), dtype=np.int8)).all()
        ):
            raise ValueError(
                "term_chart_ids must lie in the V1 driver-chart catalogue "
                f"{sorted(V1_DRIVER_CHART_IDS)}."
            )
        with np.errstate(all="ignore"):
            finite = bool(np.isfinite(loadings).all())
        if not finite:
            raise ValueError("term_loadings must be finite.")
        if bool((loadings == 0.0).any()):
            raise ValueError(
                "term_loadings must be non-zero; zero terms are removed by "
                "canonicalisation."
            )
        if n_terms > 1:
            row_of_term = np.repeat(
                np.arange(n_rows, dtype=np.int64), np.diff(offsets).astype(np.int64)
            )
            key = drivers.astype(np.int64) * 8 + charts.astype(np.int64)
            same_row = row_of_term[1:] == row_of_term[:-1]
            if not bool(np.all(key[1:][same_row] > key[:-1][same_row])):
                raise ValueError(
                    "terms within a row must be strictly increasing in "
                    "(driver_rf_id, chart_id): canonical order, no duplicates."
                )

    @property
    def num_rows(self) -> int:
        """Number of V1 target rows (one per V1 run-axis node)."""
        return int(self.row_target_rf_ids.shape[0])

    @property
    def num_terms(self) -> int:
        """Number of canonical terms across all rows."""
        return int(self.term_driver_rf_ids.shape[0])
