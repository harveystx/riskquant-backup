from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

import numpy as np
from numpy.typing import NDArray

FloatArray = NDArray[np.float64]
IntArray = NDArray[np.int64]

StressMethod = Literal[
    "gaussian_copula",
    "t_copula",
    "lower_tail_alignment",
    "comonotonic",
]

TailOrder = Literal[
    "comonotonic",
    "random",
]


@dataclass(frozen=True, slots=True, eq=False)
class DependenceStressResult:
    """
    Immutable output of one empirical dependence transformation.

    Attributes
    ----------
    stressed:
        K x S read-only float64 C-contiguous matrix. Each row holds
        exactly the observations of the corresponding base row,
        rearranged across scenarios.

    permutations:
        K x S read-only int64 C-contiguous matrix satisfying
        ``stressed[k, s] == base[k, permutations[k, s]]``.

    Notes
    -----
    Immutability is real, not nominal. ``frozen=True`` blocks attribute
    rebinding only; NumPy array *contents* stay writable unless the write
    flag is cleared. ``__post_init__`` therefore copies both inputs into
    owned C-contiguous buffers and clears the write flag on each. Writing
    into ``result.stressed`` raises ``ValueError``.

    The copy costs one K x S float64 plus one K x S int64 buffer per
    result. Measured at K=100, S=5000 that is roughly 2-4% of total
    transformation time, which is the accepted price of an output that
    can neither alias caller memory nor be mutated in place.

    ``eq=False`` is deliberate. An autogenerated ``__eq__`` would compare
    NumPy arrays with ``==``, which returns an elementwise array rather
    than a scalar bool and raises inside the field-tuple comparison.
    Equality is therefore identity-based. Compare results field-by-field
    with ``np.array_equal``.

    The permutation is retained so any stressed matrix stays reproducible
    and auditable without the original RNG state.
    """

    stressed: FloatArray
    permutations: IntArray

    def __post_init__(self) -> None:
        stressed = np.array(
            self.stressed,
            dtype=np.float64,
            order="C",
            copy=True,
        )

        permutations = np.array(
            self.permutations,
            dtype=np.int64,
            order="C",
            copy=True,
        )

        if stressed.shape != permutations.shape:
            raise ValueError(
                f"stressed shape {stressed.shape} does not match "
                f"permutations shape {permutations.shape}."
            )

        stressed.setflags(write=False)
        permutations.setflags(write=False)

        object.__setattr__(self, "stressed", stressed)
        object.__setattr__(self, "permutations", permutations)

    @property
    def shape(self) -> tuple[int, int]:
        """Result shape (K, S)."""
        return (
            int(self.stressed.shape[0]),
            int(self.stressed.shape[1]),
        )
