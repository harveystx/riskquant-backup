from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

import numpy as np
from numpy.typing import NDArray

FloatArray = NDArray[np.float64]
IntArray = NDArray[np.int64]

StressMethod = Literal[
    "gaussian_copula",
    "t_copula",
    "lower_tail_alignment",
    "comonotonic",
]

TailOrder = Literal[
    "comonotonic",
    "random",
]


@dataclass(frozen=True, slots=True, eq=False)
class DependenceStressResult:
    """
    Immutable output of one empirical dependence transformation.

    There are exactly two first-class outputs.

    Attributes
    ----------
    permutations:
        K x S read-only int64 C-contiguous matrix. Each row is a
        permutation of ``0 .. S-1``. THE PERMUTATION IS THE DEPENDENCE
        STRESS: it is the exact mathematical description of which
        original observation from each marginal was placed into each
        scenario.

    portfolio_pnl:
        S-length read-only float64 vector, the scenario aggregate::

            portfolio_pnl[s] = sum_k data[k, permutations[k, s]]

        Shape is ``(S,)`` and not ``(1, S)``. The mathematical object is
        a 1 x S scenario vector, but a flat S-vector is the natural
        NumPy shape and spares every downstream consumer a singleton
        axis. Reshape at the boundary if a 2-D form is genuinely needed.

    Notes
    -----
    The full stressed K x S matrix is NOT a field. It is an optional
    derived representation, reconstructible at any time with::

        np.take_along_axis(data, result.permutations, axis=1)

    and available through ``permutations.reconstruct_stressed``. The
    production path never materialises it, because the only quantity the
    downstream risk layer needs is the S-vector.

    This layer performs exactly one aggregation, ``sum_k``, over the
    rows of the supplied matrix. It attaches no portfolio semantics to
    those rows. The caller decides whether summing them is meaningful.

    Immutability is real, not nominal. ``frozen=True`` blocks attribute
    rebinding only; NumPy array *contents* stay writable unless the
    write flag is cleared. ``__post_init__`` copies both inputs into
    owned C-contiguous buffers and clears the write flag on each.
    Writing into either field raises ``ValueError``.

    ``eq=False`` is deliberate. An autogenerated ``__eq__`` would
    compare NumPy arrays with ``==``, which returns an elementwise array
    rather than a scalar bool and raises inside the field-tuple
    comparison. Equality is therefore identity-based; compare results
    field-by-field with ``np.array_equal``.
    """

    permutations: IntArray
    portfolio_pnl: FloatArray

    def __post_init__(self) -> None:
        permutations = np.array(
            self.permutations,
            dtype=np.int64,
            order="C",
            copy=True,
        )

        portfolio_pnl = np.array(
            self.portfolio_pnl,
            dtype=np.float64,
            order="C",
            copy=True,
        )

        if permutations.ndim != 2:
            raise ValueError(
                f"permutations must be a 2-dimensional K x S matrix; "
                f"got shape {permutations.shape}."
            )

        if portfolio_pnl.ndim != 1:
            raise ValueError(
                f"portfolio_pnl must be a 1-dimensional S-vector; "
                f"got shape {portfolio_pnl.shape}."
            )

        if portfolio_pnl.shape[0] != permutations.shape[1]:
            raise ValueError(
                f"portfolio_pnl length {portfolio_pnl.shape[0]} does not "
                f"match the scenario count {permutations.shape[1]}."
            )

        permutations.setflags(write=False)
        portfolio_pnl.setflags(write=False)

        object.__setattr__(self, "permutations", permutations)
        object.__setattr__(self, "portfolio_pnl", portfolio_pnl)

    @property
    def num_rows(self) -> int:
        """Number of empirical variables K."""
        return int(self.permutations.shape[0])

    @property
    def num_scenarios(self) -> int:
        """Number of scenarios S."""
        return int(self.permutations.shape[1])

    @property
    def shape(self) -> tuple[int, int]:
        """Shape (K, S) of the permutation matrix."""
        return (self.num_rows, self.num_scenarios)
