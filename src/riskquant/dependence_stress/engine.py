# src/riskquant/dependence_stress/engine.py

"""
Dependence-stress facade.

The engine validates the base matrix once, configures transformers, and
delegates. It holds no mutable state, no RNG, and no downstream risk
knowledge. It does not calculate VaR, ES, CSC, or any portfolio
aggregate.
"""

from __future__ import annotations

from collections.abc import Iterator
from dataclasses import dataclass

import numpy as np

from . import diagnostics as diag
from . import validation as val
from .copulas import GaussianCopula, TCopula
from .permutations import (
    DependenceTransformer,
    _apply_permutation_unchecked,
    _iter_transform_trusted,
    _transform_trusted,
)
from .tails import (
    Comonotonic,
    DualTailAlignment,
    LowerTailAlignment,
    UpperTailAlignment,
)
from .types import DependenceStressResult, FloatArray, IntArray, TailOrder

_DEFAULT_TAIL_PROBABILITY = 0.05


@dataclass(frozen=True, slots=True, kw_only=True, eq=False)
class DependenceStressEngine:
    """
    High-level empirical dependence-stress engine.

    The engine accepts a domain-agnostic K x S empirical observation
    matrix and rearranges each row across scenarios. No observation is
    created, destroyed, scaled, rounded, or interpolated.

    Every transformation returns exactly two first-class outputs:

        permutations    K x S int64   the dependence stress itself
        portfolio_pnl   S   float64   sum_k over the rearranged rows

    THE PERMUTATION IS THE DEPENDENCE STRESS.
    THE S-VECTOR IS THE STRESSED PORTFOLIO SCENARIO OUTPUT.
    THE K x S STRESSED MATRIX IS AN OPTIONAL DERIVED REPRESENTATION,
    available through ``stressed_matrix()`` and never built by the
    production path.

    Parameters
    ----------
    data:
        K x S empirical observation matrix. Rows may be subportfolio
        P&Ls, risk-factor shocks, returns, spreads, or any other
        empirical variable. The engine does not interpret them.

    Notes
    -----
    The engine owns a read-only float64 C-contiguous copy of ``data``.
    A frozen dataclass does not freeze array contents, so the copy is
    what makes the engine observationally immutable.

    The engine holds no generator. Stochastic methods take an explicit
    ``rng`` argument, so reproducibility belongs to the caller. The
    package never calls ``np.random.default_rng()`` implicitly and never
    reads global NumPy random state.

    ``eq=False`` is deliberate: an autogenerated ``__eq__`` would compare
    the ``data`` arrays with ``==`` and raise on the resulting
    elementwise array. Engines compare by identity.
    """

    data: FloatArray

    def __post_init__(self) -> None:
        object.__setattr__(
            self,
            "data",
            val.canonicalize_owned_matrix(self.data),
        )

    # ==================================================================
    # Shape
    # ==================================================================

    @property
    def num_rows(self) -> int:
        """Number of empirical variables K."""
        return int(self.data.shape[0])

    @property
    def num_scenarios(self) -> int:
        """Number of empirical scenarios S."""
        return int(self.data.shape[1])

    @property
    def shape(self) -> tuple[int, int]:
        """Observation matrix shape (K, S)."""
        return self.data.shape

    # ==================================================================
    # Transformations
    # ==================================================================

    def apply_gaussian_copula(
        self,
        latent_correlation: FloatArray,
        *,
        rng: np.random.Generator,
        audit: bool = False,
    ) -> DependenceStressResult:
        """
        Stress dependence with a Gaussian copula.

        Parameters
        ----------
        latent_correlation:
            K x K strictly positive-definite latent Gaussian correlation.
            It is not the resulting empirical Pearson or Spearman matrix.
        rng:
            Explicit generator. Required; the method is stochastic.
        audit:
            Run the full transformation audit on the result.
        """
        return self._run(
            GaussianCopula(latent_correlation=latent_correlation),
            rng=rng,
            audit=audit,
        )

    def apply_t_copula(
        self,
        latent_correlation: FloatArray,
        *,
        degrees_of_freedom: float,
        rng: np.random.Generator,
        audit: bool = False,
    ) -> DependenceStressResult:
        """
        Stress dependence with a Student-t copula.

        Lower ``degrees_of_freedom`` produces stronger symmetric tail
        dependence for a fixed latent correlation. Required and finite.
        """
        return self._run(
            TCopula(
                latent_correlation=latent_correlation,
                degrees_of_freedom=degrees_of_freedom,
            ),
            rng=rng,
            audit=audit,
        )

    def apply_lower_tail_alignment(
        self,
        tail_probability: float = _DEFAULT_TAIL_PROBABILITY,
        *,
        tail_order: TailOrder = "comonotonic",
        preserve_non_tail_order: bool = True,
        rng: np.random.Generator | None = None,
        audit: bool = False,
    ) -> DependenceStressResult:
        """
        Engineer empirical lower-tail co-occurrence directly.

        ``rng`` is required only when ``tail_order == "random"``.
        """
        return self._run(
            LowerTailAlignment(
                tail_probability=tail_probability,
                tail_order=tail_order,
                preserve_non_tail_order=preserve_non_tail_order,
            ),
            rng=rng,
            audit=audit,
        )

    def apply_upper_tail_alignment(
        self,
        tail_probability: float = _DEFAULT_TAIL_PROBABILITY,
        *,
        tail_order: TailOrder = "comonotonic",
        preserve_non_tail_order: bool = True,
        rng: np.random.Generator | None = None,
        audit: bool = False,
    ) -> DependenceStressResult:
        """Engineer empirical upper-tail co-occurrence directly."""
        return self._run(
            UpperTailAlignment(
                tail_probability=tail_probability,
                tail_order=tail_order,
                preserve_non_tail_order=preserve_non_tail_order,
            ),
            rng=rng,
            audit=audit,
        )

    def apply_dual_tail_alignment(
        self,
        lower_probability: float = _DEFAULT_TAIL_PROBABILITY,
        upper_probability: float = _DEFAULT_TAIL_PROBABILITY,
        *,
        tail_order: TailOrder = "comonotonic",
        preserve_non_tail_order: bool = True,
        rng: np.random.Generator | None = None,
        audit: bool = False,
    ) -> DependenceStressResult:
        """Engineer co-occurrence at both extremes simultaneously."""
        return self._run(
            DualTailAlignment(
                lower_probability=lower_probability,
                upper_probability=upper_probability,
                tail_order=tail_order,
                preserve_non_tail_order=preserve_non_tail_order,
            ),
            rng=rng,
            audit=audit,
        )

    def apply_comonotonic(
        self,
        *,
        audit: bool = False,
    ) -> DependenceStressResult:
        """
        Apply the deterministic extreme positive-dependence benchmark.

        No generator is required or accepted.
        """
        return self._run(
            Comonotonic(),
            rng=None,
            audit=audit,
        )

    def apply_transformer(
        self,
        transformer: DependenceTransformer,
        *,
        rng: np.random.Generator | None = None,
        audit: bool = False,
    ) -> DependenceStressResult:
        """
        Apply any object implementing ``DependenceTransformer``.
        """
        if not isinstance(transformer, DependenceTransformer):
            raise TypeError(
                "transformer must implement the DependenceTransformer protocol "
                "(requires_rng, build_permutation)."
            )

        return self._run(
            transformer,
            rng=rng,
            audit=audit,
        )

    def _run(
        self,
        transformer: DependenceTransformer,
        *,
        rng: np.random.Generator | None,
        audit: bool,
    ) -> DependenceStressResult:
        """
        Execute one transformation on the trusted engine matrix.

        The engine entered the trusted core at construction: ``data``
        was validated and canonicalized once by
        ``canonicalize_owned_matrix`` and is read-only, so no call path
        can invalidate it. Re-validating on every transformation would
        pay an O(K S) finiteness scan for a property that cannot have
        changed.
        """
        return _transform_trusted(
            self.data,
            transformer,
            rng,
            audit=audit,
        )

    # ==================================================================
    # Streaming Monte Carlo
    # ==================================================================

    def iter_results(
        self,
        transformer: DependenceTransformer,
        *,
        rng: np.random.Generator | None = None,
        n_realizations: int,
        audit: bool = False,
    ) -> Iterator[DependenceStressResult]:
        """
        Stream many stress realisations, one at a time.

        Intended for Monte Carlo estimation of the finite-sample
        distribution a stochastic stress specification induces. Memory
        stays bounded by a single realisation, so 10,000 draws cost the
        same resident memory as one:

            base data       K x S   owned once by the engine
            permutation     K x S   one live realisation
            portfolio_pnl   S       one live realisation

        Nothing is accumulated. A caller that only needs a downstream
        scalar per draw retains only that scalar::

            rng = np.random.default_rng(seed)
            tail_losses = [
                downstream_metric(result.portfolio_pnl)
                for result in engine.iter_results(
                    copula,
                    rng=rng,
                    n_realizations=10_000,
                )
            ]

        This is Monte Carlo estimation, not a bootstrap: the empirical
        observations are never resampled, only re-paired.

        The same initial generator state gives the same SEQUENCE of
        realisations. That is reproducibility of a stochastic sequence,
        not determinism of the method.

        Parameters
        ----------
        transformer:
            Object implementing ``DependenceTransformer``.
        rng:
            Explicit generator, required for a stochastic transformer.
            The whole sequence is drawn from this one generator, so its
            state advances between realisations.
        n_realizations:
            Number of realisations to yield. Zero yields nothing.
        audit:
            Run the full structural audit on every realisation. Costly;
            useful when validating a new transformer.

        Yields
        ------
        DependenceStressResult
        """
        if not isinstance(transformer, DependenceTransformer):
            raise TypeError(
                "transformer must implement the DependenceTransformer protocol "
                "(requires_rng, build_permutation)."
            )

        return _iter_transform_trusted(
            self.data,
            transformer,
            rng,
            n_realizations=n_realizations,
            audit=audit,
        )

    # ==================================================================
    # Optional derived representation
    # ==================================================================

    def stressed_matrix(
        self,
        result: DependenceStressResult,
    ) -> FloatArray:
        """
        Reconstruct the full stressed K x S matrix for a result.

        The stressed matrix is an optional derived representation, not a
        result field. Call this only for audit, diagnostics, debugging,
        demonstration, or a consumer that genuinely needs row-level
        stressed observations.

        Returns
        -------
        FloatArray
            Owned K x S matrix satisfying
            ``stressed[k, s] == data[k, permutations[k, s]]``, with every
            row's empirical marginal preserved exactly.
        """
        permutations = val.validate_permutation_matrix(
            result.permutations,
            expected_shape=self.shape,
        )

        return _apply_permutation_unchecked(self.data, permutations)

    # ==================================================================
    # Diagnostics
    # ==================================================================

    def pearson_correlation(
        self,
        data: FloatArray | None = None,
    ) -> FloatArray:
        """
        Pearson correlation of the base matrix or of a supplied matrix.
        """
        return diag.pearson_correlation(
            self.data if data is None else data,
        )

    def spearman_correlation(
        self,
        data: FloatArray | None = None,
    ) -> FloatArray:
        """
        Spearman rank correlation of the base or a supplied matrix.
        """
        return diag.spearman_correlation(
            self.data if data is None else data,
        )

    def empirical_lower_tail_cooccurrence(
        self,
        data: FloatArray | None = None,
        *,
        threshold: float = 0.05,
    ) -> FloatArray:
        """
        Finite-sample empirical lower-tail co-occurrence.

        This is not the asymptotic copula lower-tail dependence
        coefficient.
        """
        return diag.empirical_lower_tail_cooccurrence(
            self.data if data is None else data,
            threshold,
        )

    # ==================================================================
    # Audit
    # ==================================================================

    def validate_marginal_preservation(
        self,
        stressed: FloatArray,
    ) -> bool:
        """
        Verify exact row-wise marginal preservation against the base.

        Audit operation. Cost is O(K S log S).
        """
        return val.validate_marginal_preservation(
            self.data,
            stressed,
        )

    def validate_result(
        self,
        result: DependenceStressResult,
    ) -> bool:
        """
        Verify a complete result against the base matrix.

        Audit operation. Reconstructs the stressed matrix, then checks
        permutation validity, exact marginal preservation, exact
        reproduction from the recorded permutation, and agreement
        between ``result.portfolio_pnl`` and the scenario sums of the
        reconstruction.

        Cost is O(K S log S) plus one K x S allocation. Do not call it
        on every production transformation.
        """
        stressed = self.stressed_matrix(result)

        if not val.validate_transformation(
            self.data,
            stressed,
            result.permutations,
        ):
            return False

        return bool(
            np.array_equal(
                stressed.sum(axis=0),
                result.portfolio_pnl,
            )
        )

    @staticmethod
    def validate_permutation_matrix(
        permutations: IntArray,
        *,
        expected_shape: tuple[int, int] | None = None,
    ) -> IntArray:
        """
        Validate a permutation matrix. Explicit audit operation.
        """
        return val.validate_permutation_matrix(
            permutations,
            expected_shape=expected_shape,
        )
